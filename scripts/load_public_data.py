"""Import only public reference/catalog data, then evaluate labeled policy retrieval."""

import argparse, json, os
from pathlib import Path
import httpx

p = argparse.ArgumentParser()
p.add_argument("--base", default="http://127.0.0.1:8800")
p.add_argument("--catalog", action="store_true")
p.add_argument(
    "--output",
    type=Path,
    default=None,
    help="Write benchmark artifacts only when explicitly set",
)
args = p.parse_args()
root = Path(__file__).resolve().parents[1]
client = httpx.Client(base_url=args.base, timeout=300)
response = client.post(
    "/api/auth/login",
    json={
        "email": os.getenv("ADMIN_EMAIL", "admin@allocate.local"),
        "password": os.getenv("ADMIN_PASSWORD", "LocalAdmin@12345"),
    },
)
response.raise_for_status()
client.headers["Authorization"] = "Bearer " + response.json()["access_token"]


def post(path, body):
    r = client.post("/api" + path, json=body)
    r.raise_for_status()
    return r.json()


if args.catalog:
    for filename in ("esco-import.json", "onet-import.json"):
        payload = json.loads(
            (root / "data/public" / filename).read_text(encoding="utf-8")
        )
        # Bounded batches keep the API usable while importing the full technology list.
        total = 0
        for n in range(0, len(payload["rows"]), 500):
            result = post(
                "/admin/skills/import",
                {**payload, "rows": payload["rows"][n : n + 500]},
            )
            total += result["added"]
        print(filename, ":", total, "public concepts imported", flush=True)
    occupation_path = root / "data/public/esco-occupations.json"
    if occupation_path.exists():
        response = client.post(
            "/api/admin/occupations/import",
            json=json.loads(occupation_path.read_text(encoding="utf-8")),
        )
        if response.status_code == 200:
            print("Public occupations imported:", response.json()["added"], flush=True)
        elif response.status_code != 404:
            response.raise_for_status()
payload = json.loads(
    (root / "data/public/policy-import.json").read_text(encoding="utf-8")
)
payload.setdefault("publisher", "Press Information Bureau, Government of India")
payload.setdefault("scheme", "PMIS historical reference")
existing = client.get("/api/admin/policy-documents").json()
doc = next((d for d in existing if d["title"] == payload["title"]), None)
if doc is None:
    result = post("/admin/policy-documents", payload)
    print("Public reference import:", result, flush=True)
    doc = next(
        d
        for d in client.get("/api/admin/policy-documents").json()
        if d["id"] == result["id"]
    )
policies = client.get("/api/policies").json()
policy = next(
    (
        x
        for x in policies
        if x["name"] == "Historical public-reference retrieval benchmark"
    ),
    None,
)
if not policy:
    policy = post(
        "/admin/policies",
        {
            "name": "Historical public-reference retrieval benchmark",
            "document_ids": [doc["id"]],
            "config": {
                "scheme": payload["scheme"],
                "effective_date": payload["effective_date"],
            },
        },
    )
client.post(f"/api/admin/policies/{policy['id']}/approve").raise_for_status()
# Human-authored relevance labels use exact, inspected source markers. They are not generated by the retriever.
questions = [
    ("duration", "How many months do internships last?", ["12-month internships"]),
    ("stipend", "What monthly stipend is provided to interns?", ["Monthly Assistance"]),
    ("grant", "What is the one-time grant for incidentals?", ["Grant for Incidentals"]),
    ("training", "Who bears the training costs of interns?", ["Training Costs"]),
    ("insurance", "Which insurance schemes cover interns?", ["Insurance Coverage"]),
    ("age", "What age group is eligible for the pilot?", ["between 21 and 24"]),
    (
        "online",
        "Can online or distance learning students apply?",
        ["online or distance"],
    ),
    (
        "education",
        "What educational qualifications are listed?",
        ["Educational Qualifications"],
    ),
    (
        "iis",
        "Which Industry 4.0 areas does IIS train workers in?",
        ["factory automation"],
    ),
    ("swiggy", "What is the Swiggy Skills initiative?", ["Swiggy Skills"]),
    ("sankalp", "How does SANKALP support marginalized communities?", ["SANKALP"]),
    ("digital", "What is Skill India Digital used for?", ["Skill India Digital"]),
    ("no-quota", "What is the guaranteed official SC reservation percentage?", []),
    ("no-offer", "Which employer guarantees me a confirmed job offer tomorrow?", []),
]
labels = []
for key, question, markers in questions:
    relevant = [
        p["id"]
        for p in doc["passages"]
        if any(marker.casefold() in p["content"].casefold() for marker in markers)
    ]
    if markers and not relevant:
        raise RuntimeError("Missing label marker for " + key)
    labels.append(
        {
            "id": key,
            "question": question,
            "policy_id": policy["id"],
            "relevant_passage_ids": relevant,
            "supporting_passage_ids": relevant,
        }
    )
if args.output:
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / "retrieval-labels.json").write_text(
        json.dumps(labels, indent=2), encoding="utf-8"
    )
result = post("/admin/evaluate/retrieval", labels)
result["corpus"] = {
    "title": doc["title"],
    "version": doc["version"],
    "source_url": doc["source_url"],
    "passages": len(doc["passages"]),
    "label_method": "Author-inspected exact source markers; 12 answerable and 2 no-answer questions; small historical corpus, not a generalization benchmark",
}
if args.output:
    (args.output / "retrieval-results.json").write_text(
        json.dumps(result, indent=2), encoding="utf-8"
    )
print(
    json.dumps(
        {
            method: {k: v for k, v in value.items() if k != "questions"}
            for method, value in result["methods"].items()
        },
        indent=2,
    )
)
print(
    "No applicant, internship, company capacity or allocation records were created. Historical scope is for retrieval; executable eligibility coverage remains unconfirmed."
)
